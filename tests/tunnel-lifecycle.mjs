import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { Tunnel } from '../tunnel.mjs';
const base=fileURLToPath(new URL('../',import.meta.url));
const stateRoot=path.join(base,'.local/tests/lifecycle-'+randomUUID());
fs.mkdirSync(stateRoot,{recursive:true});
const mock=path.join(stateRoot,'mock.exe');
const compile=spawnSync(path.join(process.env.SystemRoot,'Microsoft.NET/Framework64/v4.0.30319/csc.exe'),['/nologo','/target:exe','/out:'+mock,path.join(base,'tests/MockTunnel.cs')],{windowsHide:true,encoding:'utf8'});
assert.equal(compile.status,0,compile.stdout+compile.stderr);
process.env.GEMINI_NGROK_PATH=mock;
process.env.HTTP_PROXY='http://localhost:1';process.env.HTTPS_PROXY='http://localhost:1';process.env.ALL_PROXY='socks5://localhost:1';
let config={publicBase:'',key:randomUUID().replaceAll('-',''),tunnelAutoStart:false};
const tunnel=new Tunnel({base,stateRoot,port:3008,getConfig:()=>config,update:value=>config={...config,...value}});
const checks=[];
try{
  await tunnel.configure({domain:'sample.ngrok-free.dev',token:'LOCAL_TEST_ONLY_'+randomUUID().replaceAll('-',''),autoStart:false});
  const first=tunnel.start();await tunnel.stop();await first;
  assert.equal(tunnel.status,'stopped');assert.equal(tunnel.child,null);
  checks.push('取消解密中的连接不会稍后启动子进程');
  process.env.ARGON_MOCK_DELAY='1500';
  const second=tunnel.start();
  for(let i=0;i<100&&!tunnel.child;i++)await new Promise(r=>setTimeout(r,25));
  assert.ok(tunnel.child);await tunnel.stop();await second;
  assert.equal(tunnel.status,'stopped');assert.equal(tunnel.child,null);assert.equal(tunnel.error,'');
  checks.push('取消启动中的连接会结束自身子进程');
  process.env.ARGON_MOCK_DELAY='30';
  await tunnel.start();assert.equal(tunnel.status,'online');assert.ok(tunnel.connectedAt);
  await tunnel.stop();assert.equal(tunnel.status,'stopped');assert.equal(tunnel.child,null);
  checks.push('在线状态与停止状态正确，子进程不继承显式代理变量');
  process.env.ARGON_MOCK_RECOVER='1';
  await tunnel.start();
  for(let i=0;i<100&&tunnel.status!=='connecting';i++)await new Promise(r=>setTimeout(r,10));
  assert.equal(tunnel.status,'connecting');assert.ok(tunnel.error);
  for(let i=0;i<100&&tunnel.status!=='online';i++)await new Promise(r=>setTimeout(r,10));
  assert.equal(tunnel.status,'online');assert.equal(tunnel.error,'');
  await new Promise(r=>setTimeout(r,350));
  assert.equal(tunnel.status,'online');assert.equal(tunnel.error,'');
  assert.ok(tunnel.events.some(event=>event.kind==='session-interrupted'));
  assert.ok(tunnel.events.some(event=>event.kind==='session-established'));
  checks.push('心跳失败后重连会恢复在线并清除错误，单次代理请求失败不会误报隧道断线');
  tunnel.status='connecting';tunnel.error='STALE';
  tunnel.confirmReachable('public-request');
  assert.equal(tunnel.status,'online');assert.equal(tunnel.error,'');assert.ok(tunnel.lastVerifiedAt);
  assert.ok(tunnel.events.every(event=>Object.keys(event).every(key=>['time','kind','level','code'].includes(key))));
  checks.push('成功公网响应可修正陈旧状态，事件记录不包含 URL、令牌或原始载荷');
  await tunnel.stop();delete process.env.ARGON_MOCK_RECOVER;
  process.env.ARGON_MOCK_ERROR='1';
  await assert.rejects(tunnel.start(),/ERR_NGROK_9010/);
  for(let i=0;i<50&&tunnel.child;i++)await new Promise(r=>setTimeout(r,20));
  assert.equal(tunnel.status,'stopped');assert.equal(tunnel.child,null);
  assert.match(tunnel.error,/账户不支持/);
  checks.push('失败连接保留明确错误并清理子进程');
  const report={checkedAt:new Date().toISOString(),passed:true,checks,externalNetworkConnections:0,mockClient:true};
  fs.writeFileSync(path.join(base,'.local/test-lifecycle-results.json'),JSON.stringify(report,null,2));
  console.log(JSON.stringify(report));
}finally{await tunnel.stop();}
